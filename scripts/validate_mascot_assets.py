"""Read-only pixel QA; writes registration metadata, never edits image pixels."""
from pathlib import Path
from PIL import Image
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'client/src/assets/mascot'
report = []
registrations = {}
for name in ['mvp', 'natural', 'interaction', 'utility']:
    path = ASSETS / f'{name}-atlas.png'
    im = Image.open(path)
    assert im.mode == 'RGBA', f'{name}: missing alpha'
    width, height = im.size
    assert width * 2 == height, f'{name}: unexpected sheet ratio'
    alpha = im.getchannel('A')
    assert alpha.getextrema() == (0, 255)
    bands, start, last = [], None, None
    for y in range(height):
        count = sum(v >= 192 for v in alpha.crop((0, y, width, y + 1)).get_flattened_data())
        if count >= 12:
            if start is None:
                start = y
            last = y
        elif start is not None and y - last >= 8:
            if last - start > 70:
                bands.append((start, last + 1))
            start = None
    if start is not None:
        bands.append((start, last + 1))
    assert len(bands) == 8, f'{name}: expected eight isolated rows, got {bands}'
    # Generated sheets have slightly irregular row placement. Keep square source
    # windows but register each row to the same 92.5% feet baseline.
    window = height / 8 if name == 'mvp' else height / 8 - 4
    starts = [max(0, (bands[row - 1][1] + 2) / height if row else 0, min((height - window) / height, (bottom - .925 * window) / height)) for row, (_, bottom) in enumerate(bands)]
    if name == 'mvp':
        starts = [row / 8 for row in range(8)]
    frames = []
    for row, y in enumerate(starts):
        hashes = []
        for col in range(4):
            cell = im.crop((col * width / 4, y * height, (col + 1) * width / 4, y * height + window))
            box = cell.getchannel('A').point(lambda a: 255 if a >= 192 else 0).getbbox()
            assert box, f'{name}/{row}/{col}: empty frame'
            margin = min(box[0], box[1], cell.width - box[2], cell.height - box[3])
            assert margin >= 1, f'{name}/{row}/{col}: content at edge ({box})'
            hashes.append(hashlib.sha256(cell.tobytes()).hexdigest())
            frames.append({'row': row, 'column': col, 'opaqueMargin': margin})
        assert len(set(hashes)) >= 3, f'{name}/{row}: repeated identical frames'
    registrations[name] = {'starts': starts, 'height': window / height}
    report.append({'asset': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                   'bytes': path.stat().st_size, 'width': width, 'height': height,
                   'rows': 8, 'columns': 4, 'frames': frames})

target = ROOT / 'client/src/mascot/atlas-registration.ts'
target.write_text('// Generated by scripts/validate_mascot_assets.py; image pixels unchanged.\n'
                  + 'export const atlasRegistration = ' + json.dumps(registrations) + ' as const;\n', encoding='utf-8')
(ROOT / 'docs/ui-customer-v2/mascot-assets-qa.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
print(f'PASS: {len(report)} RGBA atlases, 128 nonempty frames, registered margins and unique-frame checks.')
